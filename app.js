// --- Authentication ---
function checkAuthStatus() {
    const user = localStorage.getItem('agroUser');
    if (user) {
        document.getElementById('user-display-name').textContent = user;
        showPage('app-layout');
    } else {
        showPage('login-page');
    }
}

document.getElementById('login-form').addEventListener('submit', async (e) => {
    e.preventDefault();
    const username = document.getElementById('username').value;
    const password = document.getElementById('password').value;
    
    try {
        const res = await fetch(`${API_BASE}/api/login`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ username, password })
        });
        
        if (!res.ok) {
            const err = await res.json();
            alert("Login Failed: " + (err.detail || "Invalid credentials"));
            return;
        }
        
        localStorage.setItem('agroUser', username);
        document.getElementById('user-display-name').textContent = username;
        showPage('app-layout');
        loadSettings();
        loadHistory();
        fetchWeather();
    } catch (e) {
        alert("Error connecting to server.");
    }
});

document.getElementById('register-btn').addEventListener('click', async () => {
    const username = document.getElementById('username').value;
    const password = document.getElementById('password').value;
    
    if (!username || !password) {
        alert("Please enter both username and password to register.");
        return;
    }
    
    try {
        const res = await fetch(`${API_BASE}/api/register`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ username, password })
        });
        
        if (!res.ok) {
            const err = await res.json();
            alert("Registration Failed: " + (err.detail || "Error"));
            return;
        }
        
        alert("Registration successful! You can now click Sign In.");
    } catch (e) {
        alert("Error connecting to server.");
    }
});

document.getElementById('logout-btn').addEventListener('click', () => {
    localStorage.removeItem('agroUser');
    document.getElementById('username').value = '';
    document.getElementById('password').value = '';
    showPage('login-page');
});

// --- Navigation & UI ---
function showPage(pageId) {
    document.querySelectorAll('.page').forEach(p => p.classList.remove('active'));
    document.getElementById(pageId).classList.add('active');
}

function showContent(sectionId) {
    document.querySelectorAll('.content-section').forEach(s => s.classList.remove('active'));
    document.getElementById(sectionId).classList.add('active');
}

function setupEventListeners() {
    // Sidebar Navigation
    document.querySelectorAll('.nav-links li').forEach(item => {
        item.addEventListener('click', (e) => {
            document.querySelectorAll('.nav-links li').forEach(li => li.classList.remove('active'));
            const target = e.currentTarget;
            target.classList.add('active');
            showContent(`page-${target.dataset.page}`);
            
            // Close menu on click
            document.querySelector('.sidebar').classList.remove('open');
            const overlay = document.getElementById('sidebar-overlay');
            if(overlay) overlay.classList.remove('active');
        });
    });

    // Mobile Menu Toggle
    const menuBtn = document.getElementById('menu-btn');
    const sidebarOverlay = document.getElementById('sidebar-overlay');
    const sidebar = document.querySelector('.sidebar');
    
    if (menuBtn && sidebarOverlay && sidebar) {
        menuBtn.addEventListener('click', () => {
            sidebar.classList.add('open');
            sidebarOverlay.classList.add('active');
        });
        
        sidebarOverlay.addEventListener('click', () => {
            sidebar.classList.remove('open');
            sidebarOverlay.classList.remove('active');
        });
    }

    // Language Selector
    document.getElementById('lang-select').addEventListener('change', (e) => {
        currentLang = e.target.value;
        updateLanguage();
    });

    // Image Upload
    const fileUpload = document.getElementById('file-upload');
    fileUpload.addEventListener('change', handleImageUpload);
    
    document.getElementById('analyze-btn').addEventListener('click', analyzeImage);
    
    // Chat
    document.getElementById('send-btn').addEventListener('click', handleChat);
    document.getElementById('chat-input-field').addEventListener('keypress', (e) => {
        if(e.key === 'Enter') handleChat();
    });

    // Settings
    document.getElementById('save-settings-btn').addEventListener('click', () => {
        const user = localStorage.getItem('agroUser');
        const manualLoc = document.getElementById('manual-location').value;
        localStorage.setItem(`agroSettings_${user}`, JSON.stringify({ location: manualLoc }));
        
        const statusEl = document.getElementById('settings-status');
        statusEl.textContent = translations[currentLang].settings_saved;
        statusEl.style.display = 'block';
        setTimeout(() => statusEl.style.display = 'none', 3000);
        
        fetchWeather();
    });

    // Soil Planner
    const getSoilBtn = document.getElementById('get-soil-recs-btn');
    if (getSoilBtn) {
        getSoilBtn.addEventListener('click', async () => {
            const soilType = document.getElementById('soil-type-select').value;
            const btn = document.getElementById('get-soil-recs-btn');
            const resultsDiv = document.getElementById('soil-results');
            const contentDiv = document.getElementById('soil-results-content');
            
            btn.disabled = true;
            btn.textContent = "Analyzing...";
            resultsDiv.style.display = 'block';
            contentDiv.innerHTML = `<div style="text-align: center; color: var(--text-muted);">Fetching AI recommendations...</div>`;
            
            try {
                const response = await fetch(`${API_BASE}/api/recommend-crops`, {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({ soil_type: soilType, language: currentLang })
                });
                
                if (!response.ok) throw new Error("Failed to connect to backend API");
                const data = await response.json();
                
                contentDiv.innerHTML = `<div class="ai-translatable">${marked.parse ? marked.parse(data.response) : data.response.replace(/\n/g, '<br>')}</div>`;
                
                saveHistoryItem(`Soil: ${soilType}`, "AI Planner", `Got crop recommendations for ${soilType} soil.`);
            } catch (error) {
                contentDiv.innerHTML = `<div style="color: var(--danger);">Error: ${error.message}</div>`;
            }
            
            btn.disabled = false;
            btn.textContent = translations[currentLang].get_recommendations;
        });
    }

    // Fertilizer Guide
    const getFertBtn = document.getElementById('get-fertilizer-btn');
    if (getFertBtn) {
        getFertBtn.addEventListener('click', async () => {
            const cropName = document.getElementById('fert-crop-name').value.trim();
            const soilType = document.getElementById('fert-soil-select').value;
            const btn = document.getElementById('get-fertilizer-btn');
            const resultsDiv = document.getElementById('fertilizer-results');
            const contentDiv = document.getElementById('fertilizer-results-content');
            
            if (!cropName) {
                alert("Please enter a crop name.");
                return;
            }
            
            btn.disabled = true;
            btn.textContent = "Analyzing...";
            resultsDiv.style.display = 'block';
            contentDiv.innerHTML = `<div style="text-align: center; color: var(--text-muted);">Fetching AI fertilizer plan...</div>`;
            
            try {
                const response = await fetch(`${API_BASE}/api/recommend-fertilizer`, {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({ crop_name: cropName, soil_type: soilType, language: currentLang })
                });
                
                if (!response.ok) throw new Error("Failed to connect to backend API");
                const data = await response.json();
                
                contentDiv.innerHTML = `<div class="ai-translatable">${marked.parse ? marked.parse(data.response) : data.response.replace(/\n/g, '<br>')}</div>`;
                
                saveHistoryItem(`Fertilizer: ${cropName}`, "AI Planner", `Got NPK and timing schedule for ${cropName} in ${soilType} soil.`);
            } catch (error) {
                contentDiv.innerHTML = `<div style="color: var(--danger);">Error: ${error.message}</div>`;
            }
            
            btn.disabled = false;
            btn.textContent = translations[currentLang].get_fertilizer_plan;
        });
    }
}

function loadSettings() {
    const user = localStorage.getItem('agroUser');
    const settings = JSON.parse(localStorage.getItem(`agroSettings_${user}`) || '{}');
    if (settings.location) {
        document.getElementById('manual-location').value = settings.location;
    } else {
        document.getElementById('manual-location').value = '';
    }
}

// --- i18n (Localization) ---
function initLanguage() {
    const savedLang = localStorage.getItem('agroLang');
    if (savedLang && translations[savedLang]) {
        currentLang = savedLang;
        document.getElementById('lang-select').value = savedLang;
    }
    updateLanguage();
}

function updateLanguage() {
    localStorage.setItem('agroLang', currentLang);
    const dict = translations[currentLang];
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if(key === 'welcome') {
                const user = localStorage.getItem('agroUser') || 'Farmer';
                el.innerHTML = `${dict[key]}, <span id="user-display-name">${user}</span>!`;
            } else {
                el.textContent = dict[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    const aiElements = document.querySelectorAll('.ai-translatable');
    if (aiElements.length > 0) {
        Array.from(aiElements).forEach(async (el) => {
            const originalHTML = el.innerHTML;
            if (!originalHTML.trim()) return;
            
            try {
                el.style.opacity = '0.5';
                const response = await fetch(`${API_BASE}/api/translate`, {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ text: originalHTML, target_language: currentLang })
                });
                
                if (response.ok) {
                    const data = await response.json();
                    el.innerHTML = data.response;
                }
            } catch (e) {
                console.error("Translation failed", e);
            } finally {
                el.style.opacity = '1';
            }
        });
    }
}

// --- Live Weather (Backend Wrapper) ---
function fetchWeather() {
    const user = localStorage.getItem('agroUser');
    const settings = JSON.parse(localStorage.getItem(`agroSettings_${user}`) || '{}');
    
    document.getElementById('location-name').textContent = "Loading...";
    
    const fetchWeatherAPI = async (queryParams) => {
        try {
            const res = await fetch(`${API_BASE}/api/weather?${queryParams}`);
            if (!res.ok) throw new Error("Backend Weather Error");
            const data = await res.json();
            
            if (data.error) throw new Error(data.error);
            
            document.getElementById('location-name').textContent = data.name;
            document.getElementById('temp-val').textContent = Math.round(data.main.temp);
            document.getElementById('humidity-val').textContent = data.main.humidity + "%";
            document.getElementById('wind-val').textContent = data.wind.speed + " km/h";
            
            const condition = data.weather[0].main.toLowerCase();
            const guidanceEl = document.getElementById('weather-guidance');
            
            if (condition.includes('rain') || condition.includes('drizzle')) {
                guidanceEl.textContent = "Rain expected. Do not spray fertilizers or pesticides today.";
                guidanceEl.style.borderLeftColor = "var(--danger)";
                guidanceEl.style.backgroundColor = "rgba(239, 68, 68, 0.1)";
            } else if (condition.includes('clear') || condition.includes('clouds')) {
                guidanceEl.textContent = translations[currentLang].weather_advice_good;
                guidanceEl.style.borderLeftColor = "var(--accent)";
                guidanceEl.style.backgroundColor = "rgba(163, 230, 53, 0.1)";
            }
            
            // Render Forecast
            const forecastContainer = document.getElementById('forecast-container');
            if (forecastContainer && data.forecast && data.forecast.length > 0) {
                forecastContainer.innerHTML = data.forecast.slice(0, 3).map(day => {
                    const dateObj = new Date(day.date);
                    const dayName = dateObj.toLocaleDateString(currentLang === 'hi' ? 'hi-IN' : (currentLang === 'te' ? 'te-IN' : 'en-US'), { weekday: 'short', month: 'short', day: 'numeric' });
                    
                    let icon = 'cloud';
                    const cond = day.condition.toLowerCase();
                    if (cond.includes('clear')) icon = 'sun';
                    else if (cond.includes('rain') || cond.includes('drizzle')) icon = 'cloud-rain';
                    else if (cond.includes('thunderstorm')) icon = 'cloud-lightning';
                    
                    return `
                        <div class="stat-item" style="justify-content: space-between; padding: 10px 0; border-bottom: 1px solid rgba(255,255,255,0.1);">
                            <div style="display: flex; align-items: center; gap: 10px;">
                                <i data-lucide="${icon}" style="color: var(--primary);"></i>
                                <div>
                                    <h4 style="margin:0; font-size: 0.95rem;">${dayName}</h4>
                                    <span style="font-size: 0.8rem; color: var(--text-muted);">${day.condition}</span>
                                </div>
                            </div>
                            <div style="font-weight: 600; font-size: 0.9rem;">
                                ${Math.round(day.max_temp)}° <span style="color: var(--text-muted); font-weight: normal;">/ ${Math.round(day.min_temp)}°</span>
                            </div>
                        </div>
                    `;
                }).join('');
                lucide.createIcons();
            }
        } catch (e) {
            console.error(e);
            document.getElementById('location-name').textContent = "API Error";
        }
    };

    if (settings.location && settings.location.trim() !== '') {
        fetchWeatherAPI(`location=${encodeURIComponent(settings.location.trim())}`);
    } else {
        navigator.geolocation.getCurrentPosition(
            (pos) => fetchWeatherAPI(`lat=${pos.coords.latitude}&lon=${pos.coords.longitude}`),
            (err) => document.getElementById('location-name').textContent = "Location Denied"
        );
    }
}

// --- Advisory & Disease Detection (OpenAI GPT-4o) ---
let uploadedImageName = "";
let uploadedImageBase64 = "";
let uploadedImageMimeType = "";

let uploadedFileObj = null;

function handleImageUpload(e) {
    const file = e.target.files[0];
    if (file) {
        uploadedFileObj = file;
        uploadedImageName = file.name;
        const reader = new FileReader();
        reader.onload = function(event) {
            document.getElementById('preview-img').src = event.target.result;
            document.getElementById('drop-zone').classList.add('hidden');
            document.getElementById('image-preview').classList.remove('hidden');
        }
        reader.readAsDataURL(file);
    }
}

async function analyzeImage() {
    if (!uploadedFileObj) return;

    const btn = document.getElementById('analyze-btn');
    btn.textContent = "Analyzing...";
    btn.disabled = true;

    document.getElementById('drop-zone').classList.add('hidden');
    document.getElementById('image-preview').classList.remove('hidden');
    
    addChatMessage("user", `[Uploaded Image: ${uploadedImageName}] Please analyze this crop leaf.`);

    try {
        const formData = new FormData();
        formData.append("file", uploadedFileObj);
        formData.append("language", currentLang);

        const response = await fetch(`${API_BASE}/api/predict-disease`, {
            method: "POST",
            body: formData
        });
        
        if (!response.ok) throw new Error("Failed to connect to backend Vision API");
        const data = await response.json();
        
        const responseText = `**Diagnosis:** ${data.prediction}\n**Confidence:** ${(data.confidence * 100).toFixed(1)}%\n**Treatment:** ${data.treatment}\n\n*(Model: ${data.model_type})*`;
        
        addChatMessage("ai", responseText, true); // true = include expert warning
        saveHistoryItem(`Image Analysis: ${uploadedImageName}`, `${(data.confidence * 100).toFixed(0)}% Confidence`, `Analyzed via YOLO/CNN backend.`);
    } catch (error) {
        addChatMessage("ai", `Error: ${error.message}. Is the backend running?`);
    }

    btn.textContent = translations[currentLang].analyze_image;
    btn.disabled = false;
    document.getElementById('file-upload').value = "";
    uploadedFileObj = null;
}

async function handleChat() {
    const input = document.getElementById('chat-input-field');
    const text = input.value.trim();
    if (!text) return;
    
    addChatMessage("user", text);
    input.value = "";
    
    try {
        const response = await fetch(`${API_BASE}/api/chat`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ message: text, language: currentLang })
        });
        
        if (!response.ok) throw new Error("Failed to connect to backend Chat API");
        const data = await response.json();
        
        addChatMessage("ai", data.response, data.warning);
        saveHistoryItem("AI Consultation", "RAG Verified", "Text consultation via Backend AI.");
    } catch (error) {
        addChatMessage("ai", `Error: ${error.message}. Is the backend running?`);
    }
}

function addChatMessage(sender, text, includeWarning = false) {
    const chatContainer = document.getElementById('chat-messages');
    const msgDiv = document.createElement('div');
    msgDiv.className = `message ${sender}`;
    
    let contentHtml = `<div class="message-content ${sender === 'ai' ? 'ai-translatable' : ''}">${marked.parse ? marked.parse(text) : text.replace(/\n/g, '<br>')}</div>`;
    
    if (sender === 'ai' && includeWarning) {
        const warningTxt = translations[currentLang].expert_warning;
        contentHtml = `<div class="message-content">
            <div class="ai-translatable">${marked.parse ? marked.parse(text) : text.replace(/\n/g, '<br>')}</div>
            <div class="expert-warning"><i data-lucide="alert-octagon" class="icon-sm" style="display:inline; margin-bottom:-2px;"></i> <span data-i18n="expert_warning">${warningTxt}</span></div>
        </div>`;
    }
    
    msgDiv.innerHTML = contentHtml;
    chatContainer.appendChild(msgDiv);
    chatContainer.scrollTop = chatContainer.scrollHeight;
    lucide.createIcons();
}

// --- History Management ---
function saveHistoryItem(title, confidence, desc) {
    const user = localStorage.getItem('agroUser') || 'default';
    const history = JSON.parse(localStorage.getItem(`agroHistory_${user}`) || '[]');
    const date = new Date().toLocaleDateString();
    history.unshift({ title, confidence, desc, date }); 
    localStorage.setItem(`agroHistory_${user}`, JSON.stringify(history));
    loadHistory();
}

function loadHistory() {
    const user = localStorage.getItem('agroUser') || 'default';
    const list = document.getElementById('history-list');
    const history = JSON.parse(localStorage.getItem(`agroHistory_${user}`) || '[]');
    
    if (history.length === 0) {
        list.innerHTML = `<p style="color: var(--text-muted)">No past history found.</p>`;
        return;
    }
    
    list.innerHTML = history.map(item => `
        <div class="history-item">
            <div class="history-details">
                <h4>${item.title}</h4>
                <p>${item.desc} • ${item.date}</p>
            </div>
            <div class="confidence-badge">${item.confidence} Confidence</div>
        </div>
    `).join('');
}
